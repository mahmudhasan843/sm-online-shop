app.post("/api/orders", async (req, res) => {
  const client = await pool.connect();

  try {
    const body = req.body || {};
    const customer = body.customer;
    const items = body.items;

    const paymentMethod =
      cleanText(body.paymentMethod, "cod") || "cod";

    if (
      !customer ||
      !cleanText(customer.name) ||
      !cleanText(customer.phone) ||
      !cleanText(customer.address)
    ) {
      return res.status(400).json({
        error: "Customer information is required"
      });
    }

    if (!Array.isArray(items) || items.length === 0) {
      return res.status(400).json({
        error: "Order items are required"
      });
    }

    await client.query("BEGIN");

    const quantityMap = new Map();

    for (const item of items) {
      const id = cleanText(item?.id);
      const qty = Math.max(1, nonNegativeInt(item?.qty, 1));

      if (!id) {
        throw new Error("Invalid product ID");
      }

      quantityMap.set(
        id,
        (quantityMap.get(id) || 0) + qty
      );
    }

    let total = 0;
    const cleanItems = [];

    for (const [productId, qty] of quantityMap) {
      const result = await client.query(
        `
        SELECT
          id::text AS id,
          name,
          price::float AS price,
          stock
        FROM products
        WHERE id = $1
        FOR UPDATE
        `,
        [productId]
      );

      if (!result.rows.length) {
        throw new Error(`Product not found: ${productId}`);
      }

      const product = result.rows[0];

      if (Number(product.stock) < qty) {
        throw new Error(
          `Not enough stock for ${product.name}`
        );
      }

      const price = Number(product.price);
      total += price * qty;

      cleanItems.push({
        id: String(product.id),
        name: product.name,
        price,
        qty
      });
    }

    total = Math.round(total * 100) / 100;

    const orderId = makeOrderId();

    const cleanCustomer = {
      name: cleanText(customer.name),
      phone: cleanText(customer.phone),
      address: cleanText(customer.address)
    };

    await client.query(
      `
      INSERT INTO orders
        (
          id,
          created_at,
          customer,
          items,
          total,
          payment_method,
          status,
          payment_status,
          stock_restored,
          updated_at
        )
      VALUES
        ($1, NOW(), $2::jsonb, $3::jsonb, $4, $5, 'Pending',
         'Pending', FALSE, NOW())
      `,
      [
        orderId,
        JSON.stringify(cleanCustomer),
        JSON.stringify(cleanItems),
        total,
        paymentMethod
      ]
    );

    for (const item of cleanItems) {
      const stockUpdate = await client.query(
        `
        UPDATE products
        SET stock = stock - $1,
            updated_at = NOW()
        WHERE id = $2
          AND stock >= $1
        `,
        [item.qty, item.id]
      );

      if (stockUpdate.rowCount !== 1) {
        throw new Error(
          `Stock changed while placing order for ${item.name}. Please try again.`
        );
      }
    }

    await client.query("COMMIT");

    res.status(201).json({
      ok: true,
      orderId,
      total,
      status: "Pending",
      paymentStatus: "Pending"
    });
  } catch (error) {
    await client.query("ROLLBACK").catch(() => {});
    console.error("Order error:", error);

    res.status(400).json({
      error: error.message || "Could not create order"
    });
  } finally {
    client.release();
  }
});

